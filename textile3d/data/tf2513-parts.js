const inferType = (name, nameEn) => {
  const text = `${name} ${nameEn}`.toLowerCase();
  if (/密封|油封|sealing|seal\b|gasket|垫片/.test(text)) return 'seal';
  if (/齿轮|蜗杆|gear|worm/.test(text)) return 'gear';
  if (/罗拉|压辊|roller|calender roll/.test(text)) return 'roller';
  if (/带轮|皮带轮|张紧轮|导条轮|导轮|换向轮|pulley|guide wheel|wheel/.test(text)) return 'pulley';
  if (/轴|心轴|丝杆|螺杆|shaft|mandrel|screw rod|coupling/.test(text)) return 'shaft';
  if (/气缸|cylinder/.test(text)) return 'cylinder';
  if (/罩壳|箱体|箱盖|安全罩|casing|hood|gear-down box/.test(text)) return 'casing';
  if (/立柱|column/.test(text)) return 'column';
  if (/铰链|hinge/.test(text)) return 'hinge';
  if (/拉手|把手|handle/.test(text)) return 'handle';
  if (/磁性|电磁|magnet/.test(text)) return 'magnet';
  if (/弹簧|spring/.test(text)) return 'cylinder';
  if (/支座|底座|座板|固定座|安装座|轴承座|bracket|seat|mount/.test(text)) return 'bracket';
  if (/盖板|护板|固定板|安装板|调节板|垫板|平板|扁钢|刮刀|plate|flat|scraper/.test(text)) return 'plate';
  if (/盘框|底框|框|frame|rack/.test(text)) return 'panel';
  if (/圆弧斜板|弯管|软管|管|hose|pipe/.test(text)) return 'hood';
  if (/密封条|sealing strip/.test(text)) return 'seal';
  if (/脚踏板|footplate/.test(text)) return 'pressPlate';
  return 'unknown';
};

const getDims = (code, name) => {
  const source = `${code} ${name}`.replace(/×/g, 'X');
  const found = source.match(/(?:φ\s*\d+(?:\.\d+)?)|(?:M\d+(?:X\d+(?:\.\d+)?){0,2})|(?:\d+(?:\.\d+)?X\d+(?:\.\d+)?(?:X\d+(?:\.\d+)?)?)/gi) || [];
  return [...new Set(found.map((value) => value.replace(/\s+/g, '').replace(/X/g, '×')))];
};

